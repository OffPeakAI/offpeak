#!/usr/bin/env bun
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const CONTRACTS = [
  "OffpeakVault",
  "HostRegistry",
  "UsageLedger",
  "X402Escrow",
  "ChannelManager",
  "WindowMarket",
  "AuditCourt",
  "OfpkHooks",
  "FeeSplitter",
  "MockUSDG",
  "MockOFPK",
] as const

const root = new URL("..", import.meta.url).pathname

for (const name of CONTRACTS) {
  const artifact = JSON.parse(readFileSync(join(root, `contracts/out/${name}.sol/${name}.json`), "utf8"))
  const source = `// Generated by bun run abis. Do not edit.\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const\n`
  writeFileSync(join(root, `packages/abis/src/${name}.ts`), source)
}
console.log(`wrote ${CONTRACTS.length} ABIs to packages/abis/src`)
